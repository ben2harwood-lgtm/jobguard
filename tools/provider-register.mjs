import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
export function renderProviderRegister(directory = root) {
  const operations = resolve(directory, "docs/operations");
  const flows = readdirSync(operations).filter(name => name.endsWith("-data-flow.md")).sort();
  const rows = flows.map(name => {
    const bytes = readFileSync(resolve(operations, name));
    const boundary = name === "accounting-observation-data-flow.md"
      ? "Local synthetic fixtures and PostgreSQL source receipts only; live region **not chosen**"
      : "Local synthetic fixtures only; live region **not chosen**";
    return `| [${name}](${name}) | ${boundary} | ${createHash("sha256").update(bytes).digest("hex")} |`;
  });
  return `# Provider and personal-data destination register

Nothing is deployed by M0-13a ops-pack. This is an index of source-inspected,
synthetic boundaries, not provider verification or D04 approval. Every production
region below is **not chosen** until its exact processing, storage, log, backup,
subprocessor and onward-transfer destinations have independent evidence.

Generated by \`node tools/provider-register.mjs --write\`; checked by the root
Node test suite. A new or changed data-flow document requires regeneration and
review of that source. Hashes bind this index to the full per-route records,
which own categories, purposes, roles, retention/training/deletion, credentials,
fallbacks and approval gaps. Missing detail is a gate, never implicit approval.

| Route record (authoritative detail) | Current processing/storage/log/backup region status | Source SHA-256 |
| --- | --- | --- |
${rows.join("\n")}

Cross-cutting destinations (also required even where no dedicated flow exists):

| Destination / personal-data categories | Region | Current boundary / source |
| --- | --- | --- |
| Application hosting / API requests, web sessions | **not chosen** | [Hosting notes](cloudflare-hosting.md); no pilot deployment evidence |
| PostgreSQL / business, identity and audit references | **not chosen** | [Identity](identity-email-data-flow.md); local disposable test database only |
| Evidence object storage / originals and previews | **not chosen** | [Evidence storage](evidence-storage.md); private versioned synthetic fixtures |
| Logs, traces, metrics and alert delivery / operational metadata | **not chosen** | [Incident ownership](incident-ownership.md); closed-label fake sink only; no pager selected |
| Backups, replicas and restore targets / copies of all persisted categories | **not chosen** | [Restore rehearsal](synthetic-restore-rehearsal.md); disposable local fixtures only |
| Claude processing / source text and proposals | **not chosen** | [Claude](claude-data-flow.md); proposed EU names are not verified routes |
| Deepgram transcription / audio and transcripts | **not chosen** | BUILD_PLAN.md §3; no live route selected or verified by this piece |
| Payment providers / payer and payment metadata | **not chosen** | BUILD_PLAN.md M4; synthetic adapters only in this piece |
| Native sync / tenant download projections | **not chosen** | BUILD_PLAN.md M3; no live sync service verified by this piece |
| Downloads and exports / evidence, audit and commercial documents | **not chosen** | [Audit exports](audit-export-data-flow.md); receiving device and onward processing need approval |

People must choose real alert delivery and a pager, appoint the role holders,
and supply D04 and each actual destination's region and approval evidence.
Real UK deployment, TLS and secrets are founder-reserved. Running preflight
against any deployed database requires its own explicit allowance and a future
reviewed tool change: this version refuses every non-loopback database host.
G0–G5 remain closed; no real personal data, provider call or release is enabled.
`;
}
export function checkProviderRegister(directory = root) {
  if (readFileSync(resolve(directory, "docs/operations/provider-register.md"), "utf8") !== renderProviderRegister(directory))
    throw new Error("PROVIDER_REGISTER_STALE");
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv[2] === "--write") writeFileSync(resolve(root, "docs/operations/provider-register.md"), renderProviderRegister());
  else checkProviderRegister();
}
