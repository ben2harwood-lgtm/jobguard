import { execFile } from "node:child_process";
import { X509Certificate } from "node:crypto";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { promisify } from "node:util";
import { z } from "zod";
import { WormBoundaryError } from "./worm.js";

const exec = promisify(execFile);
const requestSchema = z.object({
  schemaVersion: z.literal(1), synthetic: z.literal(true),
  subject: z.enum(["manifest", "checkpoint"]), imprint: z.string().regex(/^[a-f0-9]{64}$/u),
}).strict();
export type TimestampRequest = z.infer<typeof requestSchema>;
export type TimestampResult = { status: "pending"; reason: "service_unavailable" | "invalid_response" } | {
  status: "anchored"; token: Uint8Array; query: Uint8Array; certificatePem: string; caCertificatePem: string;
  signerSha256: string; policyOid: string; algorithm: "sha256"; generatedAt: string;
  claim: "synthetic_integrity_and_existence_only";
};

/** RFC-3161 DER via the installed OpenSSL/LibreSSL tool. No endpoint or production transport. */
export class FakeTsaTimestampAdapter {
  constructor(private readonly config: {
    enabled?: boolean;
    policyOid: string;
    // This dark adapter trusts one pinned fake TSA and its local fixture CA.
    certificatePem: string;
    caCertificatePem: string;
    signerSha256: string;
    respond: (query: Uint8Array) => Promise<Uint8Array>;
  }) {}

  async anchor(input: unknown, now = new Date()): Promise<TimestampResult> {
    if (!this.config.enabled) throw new WormBoundaryError("DARK_ONLY");
    const parsed = requestSchema.safeParse(input);
    if (!parsed.success || !Number.isFinite(now.getTime()) ||
        !/^\d+(?:\.\d+)+$/u.test(this.config.policyOid)) throw new WormBoundaryError("INVALID_INPUT");
    const cert = new X509Certificate(this.config.certificatePem);
    const ca = new X509Certificate(this.config.caCertificatePem);
    if (!cert.checkIssued(ca) || !cert.verify(ca.publicKey) ||
        cert.fingerprint256.replaceAll(":", "").toLowerCase() !== this.config.signerSha256 ||
        now.getTime() < Date.parse(cert.validFrom) || now.getTime() > Date.parse(cert.validTo)) {
      throw new WormBoundaryError("INVALID_INPUT");
    }
    const dir = await mkdtemp(join(tmpdir(), "jobguard-fake-tsa-"));
    const queryPath = join(dir, "request.tsq");
    const responsePath = join(dir, "response.tsr");
    const certPath = join(dir, "signer.pem");
    const caPath = join(dir, "ca.pem");
    const tokenPath = join(dir, "token.der");
    const actualSignerPath = join(dir, "actual-signer.pem");
    const run = (args: string[]) => exec("openssl", args, { timeout: 10_000, maxBuffer: 1024 * 1024 });
    try {
      await writeFile(certPath, this.config.certificatePem, { mode: 0o600 });
      await writeFile(caPath, this.config.caCertificatePem, { mode: 0o600 });
      const { stdout: version } = await run(["version"]);
      const policyOption = version.startsWith("LibreSSL") ? "-policy" : "-tspolicy";
      await run(["ts", "-query", "-digest", parsed.data.imprint, "-sha256", policyOption,
        this.config.policyOid, "-cert", "-out", queryPath]); // Nonce is generated by OpenSSL, never omitted.
      const query = await readFile(queryPath);
      let response: Uint8Array;
      try { response = await this.config.respond(new Uint8Array(query)); }
      catch { return { status: "pending", reason: "service_unavailable" }; }
      if (!(response instanceof Uint8Array) || response.byteLength === 0 || response.byteLength > 1024 * 1024) {
        return { status: "pending", reason: "invalid_response" };
      }
      await writeFile(responsePath, response);
      try {
        // queryfile binds nonce, imprint and algorithm. Explicitly inspect the verified CMS signer too.
        await run(["ts", "-verify", "-queryfile", queryPath, "-in", responsePath, "-CAfile", caPath, "-untrusted", certPath]);
        await run(["ts", "-reply", "-in", responsePath, "-token_out", "-out", tokenPath]);
        await run(["cms", "-verify", "-inform", "DER", "-in", tokenPath, "-CAfile", caPath,
          "-purpose", "timestampsign", "-signer", actualSignerPath, "-out", join(dir, "content.der")]);
        const actual = new X509Certificate(await readFile(actualSignerPath));
        if (actual.fingerprint256 !== cert.fingerprint256) return { status: "pending", reason: "invalid_response" };
        const { stdout } = await run(["ts", "-reply", "-in", responsePath, "-text"]);
        const policy = /^Policy OID: (.+)$/mu.exec(stdout)?.[1]?.trim();
        const algorithm = /^Hash Algorithm: (.+)$/mu.exec(stdout)?.[1]?.trim();
        const stamp = /^Time stamp: (.+)$/mu.exec(stdout)?.[1]?.trim();
        const time = stamp ? Date.parse(stamp) : NaN;
        // A response must be recent, within the pinned signer's validity, and never future-dated beyond clock skew.
        if (policy !== this.config.policyOid || algorithm !== "sha256" || !Number.isFinite(time) ||
            Math.abs(time - now.getTime()) > 5 * 60 * 1000 || time < Date.parse(cert.validFrom) ||
            time > Date.parse(cert.validTo)) return { status: "pending", reason: "invalid_response" };
        return { status: "anchored", token: new Uint8Array(response), query: new Uint8Array(query),
          certificatePem: this.config.certificatePem, caCertificatePem: this.config.caCertificatePem, signerSha256: this.config.signerSha256,
          policyOid: policy, algorithm: "sha256", generatedAt: new Date(time).toISOString(),
          claim: "synthetic_integrity_and_existence_only" };
      } catch { return { status: "pending", reason: "invalid_response" }; }
    } catch { return { status: "pending", reason: "service_unavailable" }; }
    finally { await rm(dir, { recursive: true, force: true }); }
  }
}
