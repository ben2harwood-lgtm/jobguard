/** Provenance never changes the watchdog's lifecycle boundary. */
export function watchdogActive(job: Readonly<{ status: string }>): boolean {
  return job.status === "live";
}

export function watchdogUnavailableCopy(job: Readonly<{ status: string }>): string | null {
  if (watchdogActive(job)) return null;
  return ["invoiced", "paid", "lost"].includes(job.status)
    ? "This job is no longer live."
    : "Switch this job live to use the watchdog — it's free until work starts on site.";
}

